# Curates upstream Supabase Envoy config (commit 6a421fe) for this application.
# usage: python3 curate.py <upstream docker/volumes/api/envoy dir> infra/supabase/envoy
import sys, yaml
src, dst = sys.argv[1], sys.argv[2]

class D(yaml.SafeDumper): pass
def s(d, v):
    return d.represent_scalar('tag:yaml.org,2002:str', v, style='|' if '\n' in v else None)
D.add_representer(str, s)

ADMIN_ONLY = {'envoy.filters.http.rbac': {
    '@type': 'type.googleapis.com/envoy.extensions.filters.http.rbac.v3.RBACPerRoute',
    'rbac': {'rules': {'action': 'ALLOW', 'policies': {'server_only': {
        'permissions': [{'any': True}],
        'principals': [
            {'header': {'name': 'apikey', 'string_match': {'exact': '${SERVICE_ROLE_KEY}'}}},
            {'header': {'name': 'apikey', 'string_match': {'exact': '${SERVICE_ROLE_KEY_ASYMMETRIC}'}}},
        ]}}}}}}

lds = yaml.safe_load(open(f'{src}/lds.template.yaml'))
hcm = lds['resources'][0]['filter_chains'][0]['filters'][0]['typed_config']
# Never log query strings: the Realtime URL carries the API key.
hcm['access_log'][0]['typed_config']['log_format']['text_format_source']['inline_string'] = \
    '%DOWNSTREAM_REMOTE_ADDRESS_WITHOUT_PORT% [%START_TIME%] "%REQ(:METHOD)% %PATH(WQ:ORIG)% %PROTOCOL%" %RESPONSE_CODE% %BYTES_SENT%\n'
vh = hcm['route_config']['virtual_hosts'][0]
keep_prefixes = {'/auth/v1/verify', '/auth/v1/callback', '/auth/v1/.well-known/jwks.json', '/storage/v1/'}
keep_names = {'auth-v1-protected', 'realtime-v1-api-openapi-blocked', 'realtime-v1-api-tenants-blocked',
              'realtime-v1-api-protected', 'realtime-v1-ws-protected'}
routes = []
for r in vh['routes']:
    if r.get('name') in keep_names or (r.get('name') is None and r['match'].get('prefix') in keep_prefixes):
        if r['match'].get('prefix') == '/storage/v1/' or r.get('name') == 'realtime-v1-api-protected':
            # Storage and REST Broadcast are server-only (secret key), never the publishable key.
            r.setdefault('typed_per_filter_config', {}).update(ADMIN_ONLY)
        routes.append(r)
vh['routes'] = routes
with open(f'{dst}/lds.template.yaml', 'w') as f:
    f.write('# Curated from upstream docker/volumes/api/envoy/lds.template.yaml (see ../UPSTREAM.md).\n'
            '# Generated by keeping only Auth, Realtime and server-only Storage routes; Lua key\n'
            '# translation filters are unchanged from upstream.\n')
    yaml.dump(lds, f, Dumper=D, sort_keys=False, width=1000)

cds = yaml.safe_load(open(f'{src}/cds.yaml'))
cds['resources'] = [c for c in cds['resources'] if c['name'] in ('auth', 'realtime', 'storage')]
with open(f'{dst}/cds.yaml', 'w') as f:
    f.write('# Curated from upstream docker/volumes/api/envoy/cds.yaml (see ../UPSTREAM.md).\n')
    yaml.dump(cds, f, Dumper=D, sort_keys=False, width=1000)
